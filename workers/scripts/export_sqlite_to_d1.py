"""Stage 1 SQLite -> D1 export (read-only against production data).

Reads a COPY of the production SQLite file and emits:
  1. <out_dir>/foundation_import.sql  -- INSERT OR IGNORE statements for the
     Stage-1 D1 tables (subscribers, picks, prediction_memberships,
     prediction_cache, posts, deliveries).
  2. <out_dir>/row_counts.json        -- per-table source counts for validation.

Never touches the live DB: the caller must pass a copy. D1 import runs later
with `wrangler d1 execute --file`, batched to stay under D1's 100KB
statement / 100-parameter limits (batched INSERTs of 25 rows).

Usage:
  copy data\\predbot.db staging_copy.db
  python workers/scripts/export_sqlite_to_d1.py --src staging_copy.db --out workers/build
"""
from __future__ import annotations

import argparse
import json
import os
import sqlite3
import sys

TABLES = (
    "subscribers",
    "picks",
    "prediction_memberships",
    "prediction_cache",
    "posts",
    "deliveries",
)

BATCH_ROWS = 25


def quote(value):
    if value is None:
        return "NULL"
    if isinstance(value, (int, float)):
        return repr(value)
    text = str(value).replace("'", "''")
    return f"'{text}'"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", required=True, help="Path to a COPY of predbot.db")
    ap.add_argument("--out", required=True, help="Output directory")
    args = ap.parse_args()

    if os.path.abspath(args.src) in (
        os.path.abspath("predictions-bot/data/predbot.db"),
        os.path.abspath("data/predbot.db"),
    ):
        print("refusing to read a live database path directly; copy it first", file=sys.stderr)
        return 2
    os.makedirs(args.out, exist_ok=True)

    con = sqlite3.connect(args.src)
    con.row_factory = sqlite3.Row
    counts = {}
    sql_path = os.path.join(args.out, "foundation_import.sql")
    with open(sql_path, "w", encoding="utf-8") as fh:
        fh.write("-- Generated by export_sqlite_to_d1.py; safe to re-run (INSERT OR IGNORE).\n")
        for table in TABLES:
            try:
                rows = con.execute(f"SELECT * FROM {table}").fetchall()
            except sqlite3.OperationalError as exc:
                print(f"table {table} missing ({exc}); skipping", file=sys.stderr)
                counts[table] = 0
                continue
            counts[table] = len(rows)
            if not rows:
                continue
            cols = rows[0].keys()
            col_list = ", ".join(cols)
            for i in range(0, len(rows), BATCH_ROWS):
                batch = rows[i : i + BATCH_ROWS]
                values = ", ".join(
                    "(" + ", ".join(quote(r[c]) for c in cols) + ")" for r in batch
                )
                fh.write(f"INSERT OR IGNORE INTO {table} ({col_list}) VALUES {values};\n")

    with open(os.path.join(args.out, "row_counts.json"), "w", encoding="utf-8") as fh:
        json.dump(counts, fh, indent=2, sort_keys=True)
    print(json.dumps(counts, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
